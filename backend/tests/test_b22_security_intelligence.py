def get_auth_headers(client: TestClient, prefix: str = "sec_user", role: str = "admin"):
    unique = uuid.uuid4().hex[:8]
    email = f"{prefix}_{unique}@focusboard.io"
    password = "TestPassword123!"

    reg_res = client.post(
        f"{settings.API_V1_STR}/auth/register",
        json={"name": f"Sec User {unique}", "email": email, "password": password},
    )
    assert reg_res.status_code in [200, 201], reg_res.text
    data = reg_res.json()
    token = data["access_token"]
    user_id = data.get("user", {}).get("id") or data.get("id")

    # Set role in database if admin requested
    if role == "admin":
        db = SessionLocal()
        try:
            u = db.query(User).filter(User.id == user_id).first()
            if u:
                u.role = "admin"
                db.commit()
        finally:
            db.close()

    headers = {"Authorization": f"Bearer {token}"}
    return headers, user_id, email

