    list_res = client.get(
        f"{settings.API_V1_STR}/security-intelligence/events?workspace_id={ws_id}&event_type=LOGIN_FAILURE",
        headers=headers,
    )
    assert list_res.status_code == 200
    events = list_res.json()
    assert len(events) >= 3

    # Check that an alert was generated by the detection engine
    alerts_res = client.get(
        f"{settings.API_V1_STR}/security-intelligence/alerts?workspace_id={ws_id}",
        headers=headers,
    )
    assert alerts_res.status_code == 200
    alerts = alerts_res.json()
    assert len(alerts) >= 1
    assert any("Brute-Force" in a["title"] or "Threat Detected" in a["title"] for a in alerts)

